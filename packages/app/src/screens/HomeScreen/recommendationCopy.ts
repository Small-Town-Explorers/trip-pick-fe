export function pickHomeRecommendationCopy(excludedTitle?: string): HomeRecommendationCopy {
  const candidates = excludedTitle
    ? HOME_RECOMMENDATION_COPIES.filter(({ title }) => title !== excludedTitle)
    : HOME_RECOMMENDATION_COPIES;
  const index = Math.floor(Math.random() * candidates.length);

  return candidates[index] ?? HOME_RECOMMENDATION_COPIES[0];
}
